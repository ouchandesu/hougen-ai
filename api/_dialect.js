// 対象地域（ターゲット地域）の設定と、全プロンプト共通のルール文を提供する
// 将来的に他都道府県へ切り替える場合は TARGET_REGION の値だけを差し替える

// ── 対象地域の定義 ─────────────────────────────────────────
const TARGET_REGION = {
  prefecture: '愛媛県',                                        // 対象の都道府県名
  dialect:    '伊予弁',                                        // 対象の方言名
  endings:    '「〜けん」「〜ぞな」「〜よ」「〜やん」など',      // 対象方言に特有の語尾
  // 混同されやすく、対象地域の話者が普段は言わない他地域特有の言い回し
  // 他地域と共通で対象地域でも日常的に使う語（「いかん」など）はここに入れない（purityRule）
  forbidden:  '関西弁に特有の「〜やねん」「〜へん」、土佐弁、博多弁、広島弁、岡山弁、香川弁に特有の言い回し',
  // 今はほとんど使われない古い表現。無理に使うと不自然になる（naturalnessRule）
  archaic:    '「だんだん」（ありがとう）、「〜ぞなもし」など',
};

// ── ルール1：過剰変換の防止（自然さの優先）─────────────────
// 変換系のプロンプト（standard → dialect）でのみ使用する
// 無理に方言へ寄せて不自然になった過去があるため、どの指示よりも優先させる
function naturalnessRule(r = TARGET_REGION) {
  return `【自然さの優先（最優先）】
標準語のままで自然な部分は、無理に${r.dialect}へ置き換えないでください。
すべての語句を方言にする必要はなく、変える箇所が1つも無ければ原文のままで構いません。
「変えるべきところだけ変え、変えなくてよいところは変えない」を徹底し、
今の${r.prefecture}の話者が実際に口にする自然な文章にしてください。
${r.archaic}のように今はほとんど使われない表現は、原文が明らかに求めていない限り使わないでください。
この指示は、ほかのどの指示（方言の濃さを含む）よりも優先します。`;
}

// ── ルール1b：方言の濃さ（変換系のみ）────────────────────────
// 利用者が選ぶ濃さ。未知の値は normal に丸める（normalizeLevel）
const CONVERT_LEVELS = ['light', 'normal', 'strong'];

function normalizeLevel(level) {
  return CONVERT_LEVELS.includes(level) ? level : 'normal';
}

function levelRule(level, r = TARGET_REGION) {
  const rules = {
    light: `語尾・助詞・文末表現だけを${r.dialect}にし、語彙（名詞・動詞・形容詞など）は標準語のまま残してください。`,
    normal: `語尾・文末表現に加えて、${r.prefecture}の話者が日常的に言い換える語彙だけを${r.dialect}にしてください。`,
    strong: `語尾・文末表現に加えて、${r.prefecture}の話者が自然に言い換える${r.dialect}の語彙があれば、それも使ってください。
自然な言い換えが無い語は標準語のまま残し、${r.prefecture}で実際に使われていない表現を作ったり、意味が変わる言い換えをしたりはしないでください。`,
  };
  return `【方言の濃さ】
${rules[normalizeLevel(level)]}
濃さは「変えてよい範囲の上限」です。範囲内でも、「自然さの優先」に反する置き換えはしないでください。`;
}

// ── ルール2：他地域の方言の混入管理（純度管理）──────────────
// 他地域と共通でも対象地域で日常的に使う語は認める。入れすぎと、対象地域で言わない言い回しを防ぐ
function purityRule(r = TARGET_REGION) {
  return `【純度管理】
対象地域は${r.prefecture}（${r.dialect}）です。語尾や言い回しは${r.dialect}の表現（${r.endings}）を中心にしてください。
関西弁など他地域と共通の言葉でも、今の${r.prefecture}の話者が日常的に使っていて違和感のないものは使って構いません。
ただし入れすぎないでください（1つの文や解説の中で他地域寄りの言葉が目立つほど使わない）。
${r.forbidden}のように、${r.prefecture}の話者が普段言わない他地域特有の言い回しは使わないでください。
解説で他地域の方言に触れるのは、誤解を防ぐのに必要な場合だけ、短くしてください。
【確かさ】
${r.prefecture}で実際に使われているか、意味が正しいかに確信が持てない表現は、使わず・出題せず・解説で断定しないでください。
実在しない活用形や言い回し（標準語の形に語尾だけ付けた造語など）を作らないでください。
${r.archaic}のように今はあまり使われなくなった表現を扱うときは、そのことを伝え、日常的に広く使われていると誇張しないでください。`;
}

// ── ルール3：出力形式 ──────────────────────────────────────
function jsonOnlyRule() {
  return `【出力形式】
指定されたJSON形式のみを出力してください。
前置き・解説・コードブロック記号（\`\`\`）は一切含めないでください。`;
}

module.exports = {
  TARGET_REGION, CONVERT_LEVELS, normalizeLevel,
  naturalnessRule, levelRule, purityRule, jsonOnlyRule,
};
